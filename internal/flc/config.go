// LoadConfig reads a JSON config on top of the defaults (unknown fields are an error).
func LoadConfig(path string) (Config, []byte, error) {
	cfg := DefaultConfig()
	if path == "" {
		b, _ := json.Marshal(cfg)
		return cfg, b, nil
	}
	raw, err := os.ReadFile(path)
	if err != nil {
		return cfg, nil, err
	}
	dec := json.NewDecoder(bytes.NewReader(raw))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&cfg); err != nil {
		return cfg, nil, fmt.Errorf("config %s: %w", path, err)
	}
	return cfg, raw, cfg.Validate()
}

func (c *Config) Validate() error {
	for k := range c.Sampling.Weights {
		if !validKind(k) {
			return fmt.Errorf("unknown caret kind in sampling.weights: %q", k)
		}
	}
	for _, p := range append(append([]string{}, c.Secrets.Patterns...), c.Secrets.LinePatterns...) {
		if _, err := regexp.Compile(p); err != nil {
			return fmt.Errorf("secret pattern %q: %w", p, err)
		}
	}
	switch c.Discovery.BuildExcludedPolicy {
	case "keep_tagged", "skip":
	default:
		return fmt.Errorf("discovery.build_excluded_policy must be keep_tagged|skip")
	}
	switch c.Semantic.Mode {
	case "none", "best_effort", "required":
	default:
		return fmt.Errorf("semantic.mode must be none|best_effort|required")
	}
	return nil
}

// CanonicalJSON is the effective config serialized deterministically (sorted map keys via encoding/json).
func (c *Config) CanonicalJSON() []byte {
	b, _ := json.Marshal(c)
	return b
}

func (c *Config) Sha256() string {
	h := sha256.Sum256(c.CanonicalJSON())
	return hex.EncodeToString(h[:])
}

var caretKinds = []string{"line_start", "identifier_partial", "member_access", "argument_list", "composite_literal",
	"after_keyword", "after_operator", "control_flow", "func_literal", "error_handling", "log_message", "token_boundary"}

func validKind(k string) bool {
	for _, x := range caretKinds {
		if x == k {
			return true
		}
	}
	return false
}

// CaretKinds lists the caret kinds in priority order (highest first): one candidate per offset, highest wins.
func CaretKinds() []string { return append([]string{}, caretKinds...) }

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// GlobMatcher compiles '**'-style globs ("**/" matches zero or more directories).
type GlobMatcher struct{ res []*regexp.Regexp }

func NewGlobMatcher(patterns []string) *GlobMatcher {
	g := &GlobMatcher{}
	for _, p := range patterns {
		g.res = append(g.res, regexp.MustCompile(globToRegex(p)))
	}
	return g
}

func (g *GlobMatcher) Match(rel string) bool {
	for _, re := range g.res {
		if re.MatchString(rel) {
			return true
		}
	}
	return false
}

func globToRegex(p string) string {
	var b strings.Builder
	b.WriteString("^")
	for i := 0; i < len(p); {
		switch {
		case strings.HasPrefix(p[i:], "**/"):
			b.WriteString("(?:.*/)?")
			i += 3
		case strings.HasPrefix(p[i:], "/**") && i+3 == len(p):
			b.WriteString("(?:/.*)?")
			i += 3
		case strings.HasPrefix(p[i:], "**"):
			b.WriteString(".*")
			i += 2
		case p[i] == '*':
			b.WriteString("[^/]*")
			i++
		case p[i] == '?':
			b.WriteString("[^/]")
			i++
		default:
			b.WriteString(regexp.QuoteMeta(string(p[i])))
			i++
		}
	}
	b.WriteString("$")
	return b.String()
}
