// Config mirrors the C# pipeline's DatasetConfig (field names kept where the concept is shared).
type Config struct {
	ConfigVersion string          `json:"config_version"`
	RepositoryID  string          `json:"repository_id"`
	Seed          int64           `json:"seed"`
	License       LicenseConfig   `json:"license"`
	Discovery     DiscoveryConfig `json:"discovery"`
	Sampling      SamplingConfig  `json:"sampling"`
	Context       ContextConfig   `json:"context"`
	Split         SplitConfig     `json:"split"`
	Semantic      SemanticConfig  `json:"semantic"`
	Secrets       SecretsConfig   `json:"secrets"`
}

type LicenseConfig struct {
	Allowlist    []string `json:"allowlist"`
	Declared     *string  `json:"declared"`
	AllowUnknown bool     `json:"allow_unknown"`
}

type BuildContextConfig struct {
	GOOS   string   `json:"goos"`
	GOARCH string   `json:"goarch"`
	Cgo    bool     `json:"cgo"`
	Tags   []string `json:"tags"`
}

type DiscoveryConfig struct {
	Include           []string           `json:"include"`
	Exclude           []string           `json:"exclude"`
	GeneratedPatterns []string           `json:"generated_patterns"`
	GeneratedMarkers  []string           `json:"generated_markers"`
	VendoredPatterns  []string           `json:"vendored_patterns"`
	TestdataPatterns  []string           `json:"testdata_patterns"`
	TestPatterns      []string           `json:"test_patterns"`
	SkipGoIgnoredDirs bool               `json:"skip_go_ignored_dirs"`
	MaxFileBytes      int64              `json:"max_file_bytes"`
	MaxFileLineChars  int                `json:"max_file_line_chars"`
	BuildContext      BuildContextConfig `json:"build_context"`
	// keep_tagged: files excluded by build constraints under BuildContext still yield syntax samples (tag build_excluded);
	// skip: they are skipped with reason build_excluded.
	BuildExcludedPolicy string `json:"build_excluded_policy"`
}

type SamplingConfig struct {
	Weights                      map[string]float64 `json:"weights"`
	MaxSamplesPerLine            int                `json:"max_samples_per_line"`
	DropDuplicateLineTargets     bool               `json:"drop_duplicate_line_targets"`
	MaxSamplesPerFile            int                `json:"max_samples_per_file"`
	IdentifierPrefixMax          int                `json:"identifier_prefix_max"`
	MaxLineChars                 int                `json:"max_line_chars"`
	MinTargetChars               int                `json:"min_target_chars"`
	MaxTargetChars               int                `json:"max_target_chars"`
	TrivialTargetKeepProbability float64            `json:"trivial_target_keep_probability"`
	ExclusionExamplesPerReason   int                `json:"exclusion_examples_per_reason"`
}

type ContextConfig struct {
	LeftChars  int `json:"left_chars"`
	RightChars int `json:"right_chars"`
}

type SplitConfig struct {
	RepositorySplit string  `json:"repository_split"`
	RepositoryGroup *string `json:"repository_group"`
}

type SemanticConfig struct {
	// none | best_effort | required
	Mode            string   `json:"mode"`
	Policies        []string `json:"policies"`
	SubsetFraction  float64  `json:"subset_fraction"`
	MaxScopeSymbols int      `json:"max_scope_symbols"`
	MaxMembers      int      `json:"max_members"`
	MaxPackageFiles int      `json:"max_package_files"`
	// Resolve imports through ./vendor (read-only parse) when present.
	UseVendor bool `json:"use_vendor"`
}

type SecretsConfig struct {
	// High-confidence credential formats: the whole file is skipped (secret_detected).
	Patterns []string `json:"patterns"`
	// Generic credential assignments to string literals: only the affected lines are excluded (caret-level secret_detected).
	LinePatterns []string `json:"line_patterns"`
}

